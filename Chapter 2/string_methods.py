#string methods

name = "MuHaMmAd aMMAR Shah" 

# 1.  len() function (used to count charachters in variables)
length = len(name)
print(length)

# 2. lower() method (used to make all characters of your string in lower case)
print(name.lower())

# 3. upper() method (used to make all characters of your string in upper case)
print(name.upper())

# 4. title() method (First charachter Capital and all other will be small)
print(name.title())

# 5. count() method  (Count how many time a single charachter is in our string)
print(name.count("a"))
 