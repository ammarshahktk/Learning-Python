s1 = {1,2,3,4}
s2 = {3,4,5,6}
# we can perform two operations in sets Union and Intersection 
# Union -------------> for union we use "|"
union_set = s1 | s2
print("UNION SET : ")
print(union_set)

# Intersection ---------> for intersection we use '&'
intersection_set = s1 & s2
print("INTERSECTION SET : ")
print(intersection_set)